"""Validated, privacy-minimised event contract for marketing attribution."""
from __future__ import annotations

import re
from datetime import UTC, datetime
from decimal import Decimal
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field, field_validator, model_validator

EventType = Literal[
    "lead_created",
    "conversation_started",
    "evaluation_booked",
    "evaluation_attended",
    "sale_candidate",
    "sale_confirmed",
    "sale_rejected",
]
Channel = Literal["website", "whatsapp", "phone", "in_person", "manual", "unknown"]
VerificationStatus = Literal["not_required", "pending_review", "verified", "rejected"]


class MarketingAttributionEvent(BaseModel):
    """An event tied to a pseudonymous lead and an ad touchpoint.

    Raw contact details and conversation text are deliberately not accepted.
    Use a stable pseudonymous lead_key generated by the sending system.
    """

    model_config = ConfigDict(extra="forbid", str_strip_whitespace=True)

    schema_version: Literal["1"] = "1"
    event_id: str = Field(min_length=8, max_length=128, pattern=r"^[A-Za-z0-9_.:-]+$")
    event_type: EventType
    occurred_at: datetime
    lead_key: str = Field(min_length=12, max_length=128, pattern=r"^[A-Za-z0-9_.:-]+$")
    source: str = Field(default="unknown", min_length=1, max_length=64, pattern=r"^[A-Za-z0-9_.-]+$")
    channel: Channel = "unknown"

    # Ad identifiers and UTMs are allowlisted. The full landing URL and arbitrary message text are never stored.
    gclid: str | None = Field(None, max_length=512)
    gbraid: str | None = Field(None, max_length=512)
    wbraid: str | None = Field(None, max_length=512)
    fbclid: str | None = Field(None, max_length=512)
    fbc: str | None = Field(None, max_length=512)
    fbp: str | None = Field(None, max_length=512)
    ctwa_clid: str | None = Field(None, max_length=512)
    utm_source: str | None = Field(None, max_length=128)
    utm_medium: str | None = Field(None, max_length=128)
    utm_campaign: str | None = Field(None, max_length=256)
    utm_content: str | None = Field(None, max_length=256)
    utm_term: str | None = Field(None, max_length=256)
    campaign_id: str | None = Field(None, max_length=128)
    adset_id: str | None = Field(None, max_length=128)
    ad_id: str | None = Field(None, max_length=128)

    # A human-approved sale is the only event that counts as revenue.
    transaction_id: str | None = Field(None, min_length=8, max_length=128, pattern=r"^[A-Za-z0-9_.:-]+$")
    sale_value_brl: Decimal | None = Field(None, gt=Decimal("0"), le=Decimal("100000000"))
    currency: Literal["BRL"] = "BRL"
    verification_status: VerificationStatus = "not_required"
    verified_by: str | None = Field(None, max_length=128)
    evidence_ref: str | None = Field(None, max_length=256)

    @field_validator("occurred_at")
    @classmethod
    def _require_timezone_and_normalize(cls, value: datetime) -> datetime:
        if value.tzinfo is None or value.utcoffset() is None:
            raise ValueError("occurred_at must include a timezone offset")
        return value.astimezone(UTC)

    @field_validator("lead_key")
    @classmethod
    def _reject_raw_phone_numbers(cls, value: str) -> str:
        if re.fullmatch(r"\+?\d{10,15}", value):
            raise ValueError("lead_key must be a pseudonymous key, not a phone number")
        return value

    @field_validator("source")
    @classmethod
    def _normalize_source(cls, value: str) -> str:
        return value.lower()

    @field_validator("sale_value_brl")
    @classmethod
    def _normalize_currency_precision(cls, value: Decimal | None) -> Decimal | None:
        if value is None:
            return None
        rounded = value.quantize(Decimal("0.01"))
        if rounded != value:
            raise ValueError("sale_value_brl must have at most two decimal places")
        return rounded

    @model_validator(mode="after")
    def _validate_sale_workflow(self) -> "MarketingAttributionEvent":
        if self.event_type == "sale_confirmed":
            if self.verification_status != "verified":
                raise ValueError("sale_confirmed requires verification_status='verified'")
            if not self.verified_by:
                raise ValueError("sale_confirmed requires verified_by (an internal actor ID)")
            if not self.transaction_id:
                raise ValueError("sale_confirmed requires a unique transaction_id")
            if self.sale_value_brl is None:
                raise ValueError("sale_confirmed requires sale_value_brl")
            if not self.evidence_ref:
                raise ValueError("sale_confirmed requires an evidence_ref, such as a CRM/conversation record ID")
        elif self.event_type == "sale_candidate":
            if self.verification_status != "pending_review":
                raise ValueError("sale_candidate requires verification_status='pending_review'")
            if self.transaction_id is not None:
                raise ValueError("sale_candidate cannot reserve a transaction_id")
        elif self.event_type == "sale_rejected":
            if self.verification_status != "rejected":
                raise ValueError("sale_rejected requires verification_status='rejected'")
            if self.transaction_id is not None:
                raise ValueError("sale_rejected cannot carry a transaction_id")
        elif self.verification_status in {"verified", "rejected", "pending_review"}:
            raise ValueError("review statuses are only valid for sale_candidate/sale_confirmed/sale_rejected")
        return self

    def canonical_json(self) -> str:
        """Stable JSON used for idempotency checks and the audit ledger."""
        return self.model_dump_json(exclude_none=True, exclude_unset=False)

    @property
    def sale_value_minor(self) -> int | None:
        if self.sale_value_brl is None:
            return None
        return int(self.sale_value_brl * 100)
